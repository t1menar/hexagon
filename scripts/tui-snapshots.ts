/** Renders the key visual states of the agent network into docs/TUI-SNAPSHOTS.md (plain text, deterministic). */
import fs from "node:fs";
import type { AgentState, AgentStatus, StampedEvent } from "../src/contracts/types.js";
import type { DagNode } from "../src/tui/dag.js";
import { Director } from "../src/tui/director.js";
import { AnimationManager, FakeClock } from "../src/tui/motion.js";
import { renderNetwork, type Geometry } from "../src/tui/network.js";
import { renderStartup } from "../src/tui/startup.js";
import { detectCaps } from "../src/tui/theme.js";

const caps = detectCaps({ TERM: "xterm-256color", LANG: "en_US.UTF-8", COLORTERM: "truecolor" }, true);
const base: DagNode[] = [
  { id: "T-1", title: "Parse the spec", role: "implementer", deps: [], state: "queued", progress: null, provider: "anthropic", cli: "claude-code 2.1", runtimeModel: null },
  { id: "T-2", title: "Build the API", role: "implementer", deps: ["T-1"], state: "queued", progress: null, provider: "openai", cli: "codex 0.9", runtimeModel: null },
  { id: "T-3", title: "Build the UI", role: "implementer", deps: ["T-1"], state: "queued", progress: null, provider: "xai", cli: "grok 1.0", runtimeModel: null },
];
const st = (id: string, state: AgentState, extra: Record<string, unknown> = {}) => ({ task_id: id, role: "implementer", state, attempt: 1, agent: { id: "a", provider: "p", adapter: "cli" }, ...extra }) as unknown as AgentStatus;
const ev = (id: string, event: Record<string, unknown>) => ({ task_id: id, ts: new Date().toISOString(), event }) as unknown as StampedEvent;

const clock = new FakeClock();
const m = new AnimationManager({ clock, motion: "full", manual: true });
const d = new Director(m);
let nodes = base.map((n) => ({ ...n }));
const set = (id: string, patch: Partial<DagNode>) => { nodes = nodes.map((n) => (n.id === id ? { ...n, ...patch } : n)); };
const draw = (): Geometry => {
  const g = renderNetwork(nodes, { maxW: 100, maxH: 24, caps, now: clock.now(), fx: d.fx });
  d.setGeometry(g);
  return g;
};
const shot = (title: string, note: string): string => {
  const g = renderNetwork(nodes, { maxW: 100, maxH: 24, caps, now: clock.now(), fx: d.fx });
  d.setGeometry(g);
  m.particles.draw(g.canvas, clock.now(), { depth: 0, unicode: true });
  return `### ${title}\n\n${note}\n\n\`\`\`text\n${g.canvas.lines(false).join("\n")}\n\`\`\`\n`;
};
const advance = (ms: number) => { clock.advance(ms); m.step(clock.now()); };

const out: string[] = ["# Terminal snapshots\n\nGenerated by `npx tsx scripts/tui-snapshots.ts` from the real renderer, director and a deterministic clock. Colour is omitted; particles are drawn at the stated time.\n"];
const startup = (t: number) => `\`\`\`text\n${renderStartup(72, 20, t, caps, 2).lines(false).join("\n")}\n\`\`\`\n`;
out.push(`### Startup sequence (t = 450 ms, 900 ms, 1400 ms)\n\nShort brand assembly; any key skips it; \`ui.startup_animation = false\` disables it.\n\n${startup(450)}\n${startup(900)}\n${startup(1400)}`);
draw();
out.push(shot("Idle", "Nothing is running: static, zero redraws."));
set("T-1", { state: "running", progress: 0.35 }); d.status(st("T-1", "starting")); advance(250);
out.push(shot("Agent starting (activation sweep)", "A single sweep travels around the outline when an agent starts."));
d.status(st("T-1", "running")); advance(1000);
out.push(shot("Active implementation", "A short highlight arc circles the perimeter of every working agent (hold at the manager's fps)."));
set("T-1", { state: "done", progress: 1 }); set("T-2", { state: "running", progress: 0.1 }); d.status(st("T-1", "done")); d.status(st("T-2", "starting"));
advance(300);
out.push(shot("Communication / execution particles", "Particles follow the real dependency edge T-1 → T-2 (the same path that is drawn)."));
set("T-2", { state: "reviewing", progress: 0.8 }); d.status(st("T-2", "running")); d.status(st("T-2", "reviewing")); advance(800);
d.event(ev("T-2", { type: "fix_cycle", n: 1 })); advance(260);
out.push(shot("Reviewer rejection", "A stream of review particles flows from the reviewer satellite back up to the developer; amber flash on both."));
advance(3000);
d.status(st("T-2", "merging")); set("T-2", { state: "merging", progress: 0.95 }); advance(380);
out.push(shot("Reviewer approval", "Completion particles leave the satellite and continue along the outgoing edge toward integration."));
advance(4000);
set("T-3", { state: "waiting_quota", progress: 0.3, quota: "15:04~" }); d.status(st("T-3", "running")); d.status(st("T-3", "waiting_quota", { recovery: { cls: "quota_exhausted", next_retry_at: "2026-01-01T15:04:00Z", reset_source: "estimate" } })); advance(900);
out.push(shot("Quota wait", "Restrained: a slow arc, no particles, the reset time as text. The label states it resumes automatically."));
set("T-3", { state: "running", progress: 0.3, quota: null }); d.status(st("T-3", "running")); advance(350);
out.push(shot("Recovery", "On a real wait→running transition: a brand-coloured sweep and flash, and recovery particles along the incoming edge."));
advance(4000);
for (const id of ["T-1", "T-2", "T-3"]) { set(id, { state: "done", progress: 1 }); d.status(st(id, "done")); }
advance(300);
out.push(shot("Task completion", "Green flash and sweep per completed agent; the integration hub completes."));
advance(4000);
set("T-3", { state: "failed", progress: 0.3 }); d.status(st("T-3", "failed", { state_reason: "tests red" })); advance(2000);
out.push(shot("Failure (static)", "No animation: a failure never pulses or flashes after the initial log entry."));
fs.writeFileSync("docs/TUI-SNAPSHOTS.md", out.join("\n"));
console.log(`wrote docs/TUI-SNAPSHOTS.md (${out.length} sections)`);
