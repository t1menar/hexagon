// Regenerates src/agents/known-roles.ts: hashes of every role prompt ever shipped (git history + working tree),
// so `hexagon` can refresh unedited project copies of old role prompts.
import { execFileSync } from "node:child_process";
import { createHash } from "node:crypto";
import fs from "node:fs";

const h = (b) => createHash("sha256").update(b.toString("utf8").trim()).digest("hex").slice(0, 16);
const shas = new Set();
let commits = [];
try { commits = execFileSync("git", ["log", "--format=%H", "--", "templates/roles"], { encoding: "utf8" }).split(/\s+/).filter(Boolean); } catch {}
for (const c of commits) {
  for (const f of execFileSync("git", ["ls-tree", "--name-only", c, "templates/roles/"], { encoding: "utf8" }).split("\n").filter(Boolean)) {
    shas.add(h(execFileSync("git", ["show", `${c}:${f}`])));
  }
}
for (const f of fs.readdirSync("templates/roles")) shas.add(h(fs.readFileSync(`templates/roles/${f}`)));
const out = `// Generated by scripts/role-hashes.mjs. Hashes (sha256 of trimmed text, 16 hex) of every role prompt
// Hexagon has shipped: a project copy matching one was never edited, so it is refreshed to the current version.
export const SHIPPED_ROLE_HASHES = new Set<string>(${JSON.stringify([...shas].sort(), null, 2)});
`;
if (!fs.existsSync("src/agents/known-roles.ts") || fs.readFileSync("src/agents/known-roles.ts", "utf8") !== out) fs.writeFileSync("src/agents/known-roles.ts", out);
